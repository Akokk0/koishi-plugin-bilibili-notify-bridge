/**
 * 「这个地址是不是公网单播」—— 取图那道闸的判据。语义照 Python `ipaddress` 的
 * `is_global and not is_multicast`(AstrBot 那侧用的就是它),两边判的得是同一件事。
 */

import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { isPublicAddress } from "../address";

describe("isPublicAddress", () => {
	const PUBLIC = [
		"8.8.8.8",
		"93.184.216.34",
		// CGNAT(100.64/10)两侧紧挨着的那两个。
		"100.63.255.255",
		"100.128.0.0",
		// 172.16/12 两侧。
		"172.15.255.255",
		"172.32.0.1",
		// 192.0.0.0/24 里被单独放出来的那两个。
		"192.0.0.9",
		"192.0.0.10",
		"2001:4860:4860::8888",
		// IPv4 映射的 IPv6 按它代表的那个判。
		"::ffff:8.8.8.8",
		"::ffff:808:808",
		// 2001::/23 里被单独放出来的那几段。
		"2001:1::1",
		"2001:3::1",
		"2001:4:112::1",
		"2001:20::1",
		"2001:30::1",
	];
	for (const address of PUBLIC) {
		it(`${address} 是公网`, () => assert.equal(isPublicAddress(address), true));
	}

	const NOT_PUBLIC = [
		// 回环、私网、链路本地(云元数据口在这儿)、本网。
		"127.0.0.1",
		"10.0.0.1",
		"172.16.0.1",
		"172.31.255.255",
		"192.168.1.1",
		"169.254.169.254",
		"0.0.0.0",
		"0.1.2.3",
		// CGNAT。
		"100.64.0.0",
		"100.127.255.255",
		// 文档 / 测试 / 保留 / 广播。
		"192.0.0.8",
		"192.0.0.170",
		"192.0.2.1",
		"198.18.0.1",
		"198.51.100.1",
		"203.0.113.1",
		"240.0.0.1",
		"255.255.255.255",
		// 组播:Python 说它 `is_global`,得单独拦。
		"224.0.1.1",
		"239.255.255.250",
		"::1",
		"::",
		"fc00::1",
		"fd00::1",
		"fe80::1",
		"fe80::1%lo0",
		"ff02::1",
		"2001:db8::1",
		"2001::1",
		"2001:2::1",
		"2002::1",
		"100::1",
		"64:ff9b:1::1",
		"3fff::1",
		// IPv4 映射的:按它代表的那个判。
		"::ffff:127.0.0.1",
		"::ffff:7f00:1",
		"::ffff:10.0.0.1",
		"::ffff:224.0.0.1",
		// 认不出来的一律当不是公网。
		"",
		"bn.lan",
		"256.0.0.1",
		"[::1]",
	];
	for (const address of NOT_PUBLIC) {
		it(`${JSON.stringify(address)} 不是公网`, () => assert.equal(isPublicAddress(address), false));
	}
});
